"""Vanilla swing parameter profiles, generated from the game dump.

Every swing.prc in the dump was parsed and grouped by (part, bone count), then
each parameter taken as the median at that position in the chain. Grouping by
chain length and keeping the values per position is the whole point: the earlier
approach pooled a part's chains together and took one median per field, which
threw away the structure that actually makes these setups stable.

Two things vary strongly along a chain and are lost by pooling:

  goalstrength   falls steeply from root to tip - a 3-bone hair chain ships
                 500 / 300 / 200, not one value
  angle limits   widen toward the tip until it is effectively free. That same
                 3-bone hair goes from minanglez -35 to -180 by the last bone

A bone clamped to a narrow cone but only weakly held to its animated pose will
swing into its limit, get clamped, rebound and chatter - which reads in game as
the chain vibrating. Keeping the real per-position values avoids that.

Rows are ordered root first. Layout matches _PROFILE_FIELDS in
auto_swing_bones.py:

    airresistance, waterresistance, minanglez, maxanglez, minangley, maxangley,
    collisionsizetip, collisionsizeroot, frictionrate, goalstrength,
    inertialmass, localgravity, fallspeedscale, windaffect, groundhit

Angles are degrees, as stored in the prc.
"""

